def find_app_py():
    """Find app.py in the current directory."""
    candidates = [
        Path(__file__).parent / "app.py",
        Path.cwd() / "app.py",
    ]
    for p in candidates:
        if p.exists():
            return p
    raise FileNotFoundError("Could not find app.py")


def enable_stable_sources(dry_run=False):
    """Enable stable data sources by patching app.py."""
    app_py = find_app_py()
    print(f"Found app.py: {app_py}")

    content = app_py.read_text(encoding="utf-8")

    # Check if already patched
    if "enable_stable_sources.py" in content:
        print("✓ Stable data sources already enabled")
        return

    # Find insertion point (after imports, before first function)
    lines = content.split("\n")
    insert_idx = 0
    for i, line in enumerate(lines):
        if line.startswith("def ") or line.startswith("@app.route"):
            insert_idx = i
            break
        if line.strip() and not line.startswith("#") and not line.startswith("import") and not line.startswith("from"):
            insert_idx = i

    # Insert integration code
    lines.insert(insert_idx, INTEGRATION_CODE)
    new_content = "\n".join(lines)

    if dry_run:
        print("\n[DRY RUN] Would insert the following code at line", insert_idx)
        print(INTEGRATION_CODE)
        return

    # Backup original
    backup = app_py.with_suffix(".py.bak")
    app_py.rename(backup)
    print(f"✓ Backed up original to {backup}")

    # Write patched version
    app_py.write_text(new_content, encoding="utf-8")
    print(f"✓ Patched {app_py}")
    print("\n✓ Stable data sources enabled!")
    print("   Set USE_STABLE_DATA_SOURCES=false to disable")
    print("   Run 'python enable_stable_sources.py --mode rollback' to revert")


def rollback():
    """Rollback to original app.py."""
    app_py = find_app_py()
    backup = app_py.with_suffix(".py.bak")

    if not backup.exists():
        print("✗ No backup found, cannot rollback")
        return

    # Restore backup
    app_py.unlink()
    backup.rename(app_py)
    print(f"✓ Rolled back to {app_py}")
    print("✓ Original data sources restored")


