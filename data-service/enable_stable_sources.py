def main():
    parser = argparse.ArgumentParser(
        description="Enable stable multi-source data system"
    )
    parser.add_argument(
        "--mode",
        choices=["test", "enable", "rollback"],
        default="test",
        help="Operation mode",
    )
    args = parser.parse_args()

    if args.mode == "test":
        success = test_integration()
        sys.exit(0 if success else 1)
    elif args.mode == "enable":
        enable_stable_sources(dry_run=False)
    elif args.mode == "rollback":
        rollback()


if __name__ == "__main__":
    main()
